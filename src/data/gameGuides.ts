const GAME_INDEX = new Map(GAMES_LIST.map(game => [game.id, game]));

export function getGameGuide(game: GameMeta): GameGuide {
  return CURATED_GUIDES[game.id] ?? CATEGORY_GUIDES[game.category] ?? DEFAULT_GUIDE;
}

export function getGameSearchText(game: GameMeta): string {
  const categoryName = getCategoryName(game.category);
  const guide = getGameGuide(game);
  return [
    game.name,
    game.id,
    categoryName,
    game.description ?? '',
    guide.howToPlay,
    guide.tips,
  ]
    .join(' ')
    .toLowerCase();
}

export function getGameById(gameId: string): GameMeta | undefined {
  return GAME_INDEX.get(gameId);
}
